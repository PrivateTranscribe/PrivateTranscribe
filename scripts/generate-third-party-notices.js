#!/usr/bin/env node
/**
 * Writes THIRD_PARTY_NOTICES.md from resources/third-party/components.json (hand-maintained)
 * and package-lock.json (every npm package that ships on Windows x64).
 *
 * Usage:
 *   npm run notices
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ROOT = path.resolve(__dirname, "..");
const THIRD_PARTY_DIR = path.join(ROOT, "resources", "third-party");
const MANIFEST_PATH = path.join(THIRD_PARTY_DIR, "components.json");
const LOCK_PATH = path.join(ROOT, "package-lock.json");
const OUTPUT_PATH = path.join(ROOT, "THIRD_PARTY_NOTICES.md");

const NODE_MODULES = "node_modules/";
const LICENSE_FILE_PATTERN = /^(licen[cs]e|copying)/i;
const NOTICE_FILE_PATTERN = /^notice/i;
const LICENSE_PATH_PATTERN = /^licenses\/\S+$/;

const INTRO = [
  "# Third-party notices",
  "",
  "PrivateTranscribe contains software, fonts and a model made by others. This file lists every third-party part that the Windows installer puts on the computer, with its licence, and then what the app can download later. It is installed with the app as `resources/THIRD_PARTY_NOTICES.md`.",
  "",
  "Each entry links to where the source of that part is published, at the shipped version where that is known; entries say when it is not. The projects inside Electron are listed with their homepages in `LICENSES.chromium.html`, next to `PrivateTranscribe.exe`.",
  "",
  "This file is generated by `npm run notices` from `resources/third-party/components.json` and `package-lock.json`.",
].join("\n");

function loadManifest(manifestPath = MANIFEST_PATH) {
  return JSON.parse(fs.readFileSync(manifestPath, "utf8"));
}

function normalizeText(text) {
  const withoutBom = text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
  // Prettier strips trailing spaces even inside code blocks; they carry no licence meaning.
  return withoutBom
    .split(/\r\n?|\n/)
    .map((line) => line.trimEnd())
    .join("\n")
    .trimEnd();
}

function compareStrings(a, b) {
  if (a < b) return -1;
  return a > b ? 1 : 0;
}

function globToRegExp(glob) {
  let pattern = "";
  for (let i = 0; i < glob.length; i++) {
    const char = glob[i];
    if (char === "*" && glob[i + 1] === "*") {
      const crossesFolders = glob[i + 2] === "/";
      pattern += crossesFolders ? "(?:.*/)?" : ".*";
      i += crossesFolders ? 2 : 1;
    } else if (char === "*") {
      pattern += "[^/]*";
    } else if (char === "?") {
      pattern += "[^/]";
    } else {
      pattern += char.replace(/[.+^${}()|[\]\\]/g, "\\$&");
    }
  }
  return new RegExp(`^${pattern}$`, "i");
}

/** Returns the shipped paths (relative to the packaged resources folder) that no component covers. */
function findUncoveredFiles(shippedPaths, manifest) {
  const matchers = manifest.components
    .flatMap((component) => component.files || [])
    .map(globToRegExp);
  return shippedPaths.filter((shippedPath) => {
    const posixPath = shippedPath.replace(/\\/g, "/");
    return !matchers.some((matcher) => matcher.test(posixPath));
  });
}

function allowsPlatform(values, wanted) {
  if (!Array.isArray(values) || values.length === 0) return true;
  if (values.includes(`!${wanted}`)) return false;
  const allowed = values.filter((value) => !value.startsWith("!"));
  return allowed.length === 0 || allowed.includes(wanted);
}

/** Non-dev lock packages that npm installs on win32 x64, one per name@version, sorted by name. */
function selectShippedPackages(lock) {
  const byId = new Map();
  for (const [location, entry] of Object.entries(lock.packages || {})) {
    if (!location || entry.dev || entry.link) continue;
    if (!allowsPlatform(entry.os, "win32") || !allowsPlatform(entry.cpu, "x64")) continue;
    const name =
      entry.name || location.slice(location.lastIndexOf(NODE_MODULES) + NODE_MODULES.length);
    const id = `${name}@${entry.version}`;
    if (!byId.has(id)) byId.set(id, { id, name, version: entry.version, entry, locations: [] });
    byId.get(id).locations.push(location);
  }
  return [...byId.values()].sort(
    (a, b) => compareStrings(a.name, b.name) || compareStrings(a.version, b.version)
  );
}

function declaredLicense(packageJson, lockEntry) {
  const value = packageJson?.license ?? lockEntry.license;
  if (typeof value === "string" && value.trim()) return value.trim();
  if (value && typeof value.type === "string") return value.type;
  const legacy = Array.isArray(packageJson?.licenses) ? packageJson.licenses : [];
  const types = legacy
    .map((item) => (typeof item === "string" ? item : item?.type))
    .filter(Boolean);
  return types.length > 0 ? types.join(" OR ") : null;
}

function authorName(author) {
  const raw = typeof author === "string" ? author : author?.name;
  if (!raw) return null;
  return (
    raw
      .replace(/<[^>]*>/g, "")
      .replace(/\([^)]*\)/g, "")
      .trim() || null
  );
}

function repositoryUrl(packageJson, lockEntry) {
  const repository = packageJson?.repository;
  const raw = typeof repository === "string" ? repository : repository?.url;
  if (!raw) return packageJson?.homepage || lockEntry.resolved || null;
  const url = raw
    .trim()
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^ssh:\/\/git@/, "https://")
    .replace(/^git@([^:]+):/, "https://$1/")
    .replace(/\.git$/, "");
  const shorthand = url.match(/^(github|gitlab|bitbucket):(.+)$/);
  if (shorthand) {
    const host = shorthand[1] === "bitbucket" ? "bitbucket.org" : `${shorthand[1]}.com`;
    return `https://${host}/${shorthand[2]}`;
  }
  return /^[\w.-]+\/[\w.-]+$/.test(url) ? `https://github.com/${url}` : url;
}

function readPackageLicenseText(dir, license) {
  const wantsNotice = /Apache-2\.0/i.test(license || "");
  const texts = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((item) => item.isFile())
    .map((item) => item.name)
    .filter(
      (name) => LICENSE_FILE_PATTERN.test(name) || (wantsNotice && NOTICE_FILE_PATTERN.test(name))
    )
    .sort(compareStrings)
    .map((name) => ({ name, text: normalizeText(fs.readFileSync(path.join(dir, name), "utf8")) }));
  if (texts.length === 0) return null;
  if (texts.length === 1) return texts[0].text;
  return texts.map(({ name, text }) => `--- ${name} ---\n\n${text}`).join("\n\n");
}

function describePackage(pkg) {
  for (const location of pkg.locations) {
    const dir = path.join(ROOT, location);
    const packageJsonPath = path.join(dir, "package.json");
    if (!fs.existsSync(packageJsonPath)) continue;
    const packageJson = JSON.parse(fs.readFileSync(packageJsonPath, "utf8"));
    const license = declaredLicense(packageJson, pkg.entry);
    return {
      ...pkg,
      license,
      author: authorName(packageJson.author),
      repository: repositoryUrl(packageJson, pkg.entry),
      licenseText: readPackageLicenseText(dir, license),
    };
  }
  // An optional package npm skipped on this machine is still listed, from its lock entry.
  return {
    ...pkg,
    license: declaredLicense(null, pkg.entry),
    author: null,
    repository: pkg.entry.resolved || null,
    licenseText: null,
  };
}

function readLicenseFile(relativePath, record) {
  if (!record) throw new Error(`${relativePath} is used but has no entry in licenseFiles`);
  const bytes = fs.readFileSync(path.join(THIRD_PARTY_DIR, relativePath));
  const sha256 = crypto.createHash("sha256").update(bytes).digest("hex");
  if (sha256 !== record.sha256) {
    throw new Error(`${relativePath} does not match its recorded sha256; copy it again byte-exact`);
  }
  return normalizeText(bytes.toString("utf8"));
}

function fence(text) {
  const longestRun = Math.max(0, ...(text.match(/`+/g) || []).map((run) => run.length));
  const marks = "`".repeat(Math.max(3, longestRun + 1));
  return `${marks}text\n${text}\n${marks}`;
}

function formatUrl(value) {
  if (/^https?:\/\/[^\s<>]+$/.test(value)) return `<${value}>`;
  return /[<>]/.test(value) ? `\`${value}\`` : value;
}

function asList(value) {
  if (value === undefined || value === null) return [];
  return Array.isArray(value) ? value : [value];
}

function renderComponent(component, context) {
  const lines = [`### ${component.name}`, ""];
  if (component.note) lines.push(component.note, "");
  if (component.version) lines.push(`- Version: ${component.version}`);
  lines.push(`- Licence: \`${component.license}\``);
  for (const copyright of component.copyright || []) lines.push(`- ${copyright}`);
  if (component.source) lines.push(`- Source: ${formatUrl(component.source)}`);
  if (component.licenseUrl) lines.push(`- Licence terms: ${formatUrl(component.licenseUrl)}`);
  if (component.files) {
    lines.push(`- Files: ${component.files.map((file) => `\`${file}\``).join(", ")}`);
  }

  for (const licenseText of asList(component.licenseText)) {
    lines.push("");
    if (LICENSE_PATH_PATTERN.test(licenseText)) {
      const record = context.manifest.licenseFiles[licenseText];
      readLicenseFile(licenseText, record);
      context.usedLicenseFiles.add(licenseText);
      lines.push(`Licence text: ${record.title}, under "Full licence texts" at the end.`);
      continue;
    }
    const text = normalizeText(licenseText);
    if (context.inlineTexts.has(text)) {
      lines.push(`Licence text: the same as for ${context.inlineTexts.get(text)} above.`);
    } else {
      context.inlineTexts.set(text, component.name);
      lines.push(fence(text));
    }
  }
  return lines.join("\n");
}

/** Bundled components whose files sit inside the package, like FFmpeg inside ffmpeg-static. */
function componentsInside(packageName, manifest) {
  const prefixes = ["app.asar/", "app.asar.unpacked/"].map((archive) =>
    `${archive}node_modules/${packageName}/`.toLowerCase()
  );
  return manifest.components
    .filter((component) =>
      component.files.some((file) =>
        prefixes.some((prefix) => file.toLowerCase().startsWith(prefix))
      )
    )
    .map((component) => component.name);
}

function renderPackages(packages, context) {
  const groups = new Map();
  for (const pkg of packages) {
    if (!pkg.licenseText) continue;
    if (!groups.has(pkg.licenseText)) {
      groups.set(pkg.licenseText, { number: groups.size + 1, ids: [] });
    }
    groups.get(pkg.licenseText).ids.push(pkg.id);
  }

  const list = packages.map((pkg) => {
    const parts = [`\`${pkg.license || "no licence declared"}\``];
    if (!pkg.licenseText) parts.push(pkg.author ? `by ${pkg.author}` : "author not named");
    if (pkg.repository) parts.push(formatUrl(pkg.repository));
    parts.push(
      pkg.licenseText
        ? `licence text ${groups.get(pkg.licenseText).number}`
        : "no licence file in the package"
    );
    const inside = componentsInside(pkg.name, context.manifest);
    if (inside.length > 0) parts.push(`contains ${inside.join(", ")} (see above)`);
    return `- \`${pkg.id}\`: ${parts.join(", ")}`;
  });

  const texts = [...groups.entries()].map(([text, group]) => {
    const users = group.ids.map((id) => `\`${id}\``).join(", ");
    const longText = context.longTexts.get(text);
    if (longText) context.usedLicenseFiles.add(longText.relativePath);
    const body = longText
      ? `The same as ${longText.title}, under "Full licence texts".`
      : fence(text);
    return [`#### Licence text ${group.number}`, "", `Used by ${users}.`, "", body].join("\n");
  });

  return [
    "## npm packages",
    "",
    "This is the app's production dependency tree for Windows x64, taken from `package-lock.json`. The packages ship inside `app.asar` or `app.asar.unpacked`, or are built into the app's interface code; the packaging rules leave out a few, such as type definitions. Each line gives the version, the licence the package declares, its repository, which licence text below is its own and any bundled component above that it contains.",
    "",
    ...list,
    "",
    "### Licence texts of npm packages",
    "",
    texts.join("\n\n"),
  ].join("\n");
}

function renderLongTexts(context) {
  const sections = Object.entries(context.manifest.licenseFiles)
    .filter(([relativePath]) => context.usedLicenseFiles.has(relativePath))
    .map(([relativePath, record]) =>
      [
        `### ${record.title}`,
        "",
        `Source: ${formatUrl(record.source)}`,
        "",
        fence(readLicenseFile(relativePath, record)),
      ].join("\n")
    );
  return ["## Full licence texts", "", sections.join("\n\n")].join("\n");
}

function generateNotices() {
  const manifest = loadManifest();
  const lock = JSON.parse(fs.readFileSync(LOCK_PATH, "utf8"));
  for (const component of manifest.components) {
    if (!Array.isArray(component.files) || component.files.length === 0) {
      throw new Error(`Component "${component.name}" needs a files list`);
    }
  }

  const packages = selectShippedPackages(lock).map(describePackage);
  const undeclared = packages.filter((pkg) => !pkg.license && !pkg.licenseText);
  if (undeclared.length > 0) {
    throw new Error(
      `No licence field and no licence file: ${undeclared.map((pkg) => pkg.id).join(", ")}`
    );
  }

  const context = {
    manifest,
    usedLicenseFiles: new Set(),
    inlineTexts: new Map(),
    longTexts: new Map(
      Object.entries(manifest.licenseFiles).map(([relativePath, record]) => [
        readLicenseFile(relativePath, record),
        { relativePath, title: record.title },
      ])
    ),
  };

  const markdown = [
    INTRO,
    "## Components bundled with PrivateTranscribe",
    manifest.components.map((component) => renderComponent(component, context)).join("\n\n"),
    "## Downloaded by the app",
    "The app downloads these later, when a feature that needs them is set up or first used. They are not part of the installer.",
    manifest.downloaded.map((item) => renderComponent(item, context)).join("\n\n"),
    renderPackages(packages, context),
    renderLongTexts(context),
  ].join("\n\n");

  return {
    markdown: `${markdown}\n`,
    packageCount: packages.length,
    withoutLicenseFile: packages.filter((pkg) => !pkg.licenseText).map((pkg) => pkg.id),
  };
}

function main() {
  try {
    const result = generateNotices();
    fs.writeFileSync(OUTPUT_PATH, result.markdown);
    console.log(
      `[notices] Wrote THIRD_PARTY_NOTICES.md (${Buffer.byteLength(result.markdown)} bytes): ` +
        `${result.packageCount} npm packages, ${result.withoutLicenseFile.length} without a licence file.`
    );
    if (result.withoutLicenseFile.length > 0) {
      console.log(`[notices] No licence file: ${result.withoutLicenseFile.join(", ")}`);
    }
  } catch (error) {
    console.error(`[notices] ${error.message}`);
    process.exitCode = 1;
  }
}

if (require.main === module) {
  main();
}

module.exports = {
  findUncoveredFiles,
  loadManifest,
  selectShippedPackages,
};
